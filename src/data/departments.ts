const DICTIONARY = new Map<string, string>();
for (const [dept, words] of Object.entries(WORDS)) {
  for (const w of words) DICTIONARY.set(normalize(w), dept);
}

/** True when the whole phrase is a product we know, e.g. "שקיות זבל". */
export function isKnownProduct(name: string) {
  return DICTIONARY.has(normalize(name));
}

/** Canonical form used for duplicate detection, ids and dictionary lookups. */
export function normalize(name: string): string {
  return name
    .replace(/[֑-ׇ]/g, '') // niqqud and cantillation
    .replace(/[׳`]/g, "'")
    .replace(/[״“”]/g, '"')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

/**
 * Best guess for a product's department: family override, exact dictionary
 * match, then the longest dictionary phrase the name starts with or contains.
 */
export function guessDepartment(norm: string, overrides: Map<string, string>): string {
  const own = overrides.get(norm);
  if (own) return currentDept(own);
  const exact = DICTIONARY.get(norm);
  if (exact) return exact;
  let best = '';
  let bestDept = OTHER;
  for (const [word, dept] of DICTIONARY) {
    if (word.length > best.length && (norm.startsWith(word + ' ') || norm.includes(word))) {
      best = word;
      bestDept = dept;
    }
  }
  // Ignore very short accidental matches inside other words.
  return best.length >= 3 ? bestDept : OTHER;
}

/** Departments in the family's order, with any new defaults appended. */
export function orderedDepartments(familyOrder: string[] | undefined): string[] {
  const order = (familyOrder ?? []).map(currentDept).filter((d, i, a) => DEFAULT_DEPARTMENTS.includes(d) && a.indexOf(d) === i);
  for (const d of DEFAULT_DEPARTMENTS) if (!order.includes(d)) order.push(d);
  return order;
}
