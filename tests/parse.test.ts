import { describe, expect, it } from 'vitest';
import { parseItems } from '../src/data/parse';

const one = (text: string) => parseItems(text)[0];

describe('parseItems', () => {
  it.each([
    ['קילו בשר טחון', 'בשר טחון', 'קילו'],
    ['חצי קילו עגבניות', 'עגבניות', 'חצי קילו'],
    ['2 ק"ג תפוחי אדמה', 'תפוחי אדמה', '2 ק"ג'],
    ['קילו וחצי עוף', 'עוף', 'קילו וחצי'],
    ['שתי חבילות במבה', 'במבה', 'שתי חבילות'],
    ['חבילה של ביסלי', 'ביסלי', 'חבילה'],
    ['3 חלב', 'חלב', '3'],
    ['לחם 2', 'לחם', '2'],
    ['בשר טחון קילו', 'בשר טחון', 'קילו'],
    ['עגבניות 2 קילו', 'עגבניות', '2 קילו'],
    ['ביצים x12', 'ביצים', '12'],
    ['מגש ביצים', 'ביצים', 'מגש'],
    ['ליטר חלב', 'חלב', 'ליטר'],
    ['חלב 3%', 'חלב 3%', ''],
    ['שקיות זבל', 'שקיות זבל', ''],
    ['שמפו', 'שמפו', ''],
    ['קילו', 'קילו', ''],
  ])('%s → %s / %s', (text, name, qty) => {
    expect(one(text)).toEqual({ name, qty });
  });

  it('splits several products and drops duplicates', () => {
    expect(parseItems('חלב, לחם 2\nחלב\n- ביצים')).toEqual([
      { name: 'חלב', qty: '' },
      { name: 'לחם', qty: '2' },
      { name: 'ביצים', qty: '' },
    ]);
  });
});
